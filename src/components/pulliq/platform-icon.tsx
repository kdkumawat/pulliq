/**
 * Platform mark: a real brand SVG icon on a tinted rounded square.
 * Adapts to dark/light mode via currentColor for monochrome brands.
 */
export function PlatformIcon({
  platform,
  className,
  withRing,
}: {
  platform: PlatformId;
  className?: string;
  withRing?: boolean;
}) {
  const Icon = ICONS[platform] ?? ICONS.unknown;
  const color = BRAND_COLOR[platform] ?? BRAND_COLOR.unknown;
  const isMonochrome = color === "currentColor";

  return (
    <span
      className={cn(
        "inline-flex items-center justify-center rounded-lg leading-none",
        className
      )}
      style={{
        backgroundColor: isMonochrome
          ? "color-mix(in srgb, currentColor 10%, transparent)"
          : `color-mix(in srgb, ${color} 14%, transparent)`,
        color: color,
        boxShadow: withRing
          ? `inset 0 0 0 1px color-mix(in srgb, ${isMonochrome ? "currentColor" : color} 26%, transparent)`
          : undefined,
      }}
      aria-hidden="true"
    >
      <Icon className="h-[65%] w-[65%]" />
    </span>
  );
}

